def setup(ws, headers, widths, title):
    ws.sheet_view.rightToLeft = True
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    c = ws.cell(1, 1, title)
    c.font = Font(name=F, bold=True, size=14, color=NAVY)
    c.alignment = Alignment(horizontal="right", vertical="center", readingOrder=2)
    ws.row_dimensions[1].height = 28
    for i, (h, w) in enumerate(zip(headers, widths), 1):
        cell = ws.cell(2, i, h)
        cell.font = hdr_font; cell.fill = hdr_fill; cell.alignment = center; cell.border = border
        ws.column_dimensions[cell.column_letter].width = w
    ws.freeze_panes = "A3"

